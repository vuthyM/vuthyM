#!/usr/bin/env python3
"""Writes the @font-face rules for the extra typeface sets (src/ui/fonts.css, below the three fonts DM Forge started with).
Each file is embedded by the build, so every set works offline. A face's size-adjust evens out how big each font looks next to
the others; a weight range on the heaviest face stops the browser faking bold where a font has no bold of its own."""
import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
CSS = os.path.join(ROOT, 'src', 'ui', 'fonts.css')
MARK = '/* ---- typeface sets (generated by tools/gen-fonts.py) ---- */'
# family, package, [(weight, style, range or None)], size-adjust %
FACES = [
  ('Cinzel', 'cinzel', [(600, 'normal', None), (700, 'normal', '700 800')], 90),
  ('Source Sans 3', 'source-sans-3', [(400, 'normal', None), (500, 'normal', None), (600, 'normal', None), (700, 'normal', None), (400, 'italic', None)], 104),
  ('Alegreya', 'alegreya', [(600, 'normal', None), (700, 'normal', '700 800')], 108),
  ('Alegreya Sans', 'alegreya-sans', [(400, 'normal', None), (500, 'normal', None), (700, 'normal', None), (400, 'italic', None)], 106),
  ('DM Mono', 'dm-mono', [(400, 'normal', None), (500, 'normal', '500 700')], 100),
  ('Literata', 'literata', [(600, 'normal', None), (700, 'normal', '700 800')], 96),
  ('Atkinson Hyperlegible', 'atkinson-hyperlegible', [(400, 'normal', None), (700, 'normal', '700 800'), (400, 'italic', None)], 100),
  ('JetBrains Mono', 'jetbrains-mono', [(400, 'normal', None), (600, 'normal', '600 800')], 94),
  ('Young Serif', 'young-serif', [(400, 'normal', '400 800')], 100),
  ('Figtree', 'figtree', [(400, 'normal', None), (500, 'normal', None), (600, 'normal', None), (700, 'normal', None), (400, 'italic', None)], 100),
  ('Fira Code', 'fira-code', [(400, 'normal', None), (600, 'normal', '600 800')], 94),
  ('Plus Jakarta Sans', 'plus-jakarta-sans', [(600, 'normal', None), (700, 'normal', '700 800')], 95),
  ('Inter', 'inter', [(400, 'normal', None), (500, 'normal', None), (600, 'normal', None), (700, 'normal', None), (400, 'italic', None)], 100),
  ('Bricolage Grotesque', 'bricolage-grotesque', [(600, 'normal', None), (700, 'normal', '700 800')], 100),
  ('DM Sans', 'dm-sans', [(400, 'normal', None), (500, 'normal', None), (600, 'normal', None), (700, 'normal', None), (400, 'italic', None)], 100),
]
out = [MARK]
for fam, pkg, faces, adj in FACES:
    for w, style, rng in faces:
        f = '../../node_modules/@fontsource/%s/files/%s-latin-%d-%s.woff2' % (pkg, pkg, w, style)
        assert os.path.exists(os.path.join(ROOT, 'src', 'ui', f)), f
        out.append("@font-face{font-family:'%s';font-style:%s;font-weight:%s;font-display:swap;%ssrc:url('%s') format('woff2')}" % (fam, style, rng or w, 'size-adjust:%d%%;' % adj if adj != 100 else '', f))
src = open(CSS).read()
if MARK in src: src = src[:src.index(MARK)].rstrip('\n') + '\n'
open(CSS, 'w').write(src + '\n'.join(out) + '\n')
print(len(out) - 1, 'faces')
