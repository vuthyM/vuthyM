/* "Try the demo vault": the fully loaded campaign opens straight in, with every tool having something to show. */
import { createRequire } from 'node:module';
import path from 'node:path'; import url from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright');
const here = path.dirname(url.fileURLToPath(import.meta.url));
const results = [];
const check = (name, cond, extra) => { results.push(!!cond); console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '  ' + (extra ?? ''))); };

const b = await chromium.launch({ args: ['--no-sandbox'] });
const pg = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = [];
pg.on('pageerror', e => errors.push(e.message));
pg.on('console', m => { if (m.type() === 'error' && !/fonts\.g|Failed to load|ERR_/.test(m.text())) errors.push(m.text()); });
await pg.goto('file://' + path.join(here, '..', 'dist', 'DM-Forge.html'));
await pg.click('text=Try the demo vault');
await pg.waitForSelector('.sidebar');
check('the demo opens straight into the campaign (no folder-mapping step)', await pg.evaluate(() => window.__dmforge.S.screen) === 'app');
const nav = await pg.$$eval('.nav-btn', els => els.map(e => e.textContent.trim()));
const count = label => { const n = nav.find(t => t.startsWith(label)); return n ? parseInt(n.replace(/\D+/g, ''), 10) : 0; };
check('16 NPCs, 4 players, 9 places, 5 factions, 7 threads, 6 sessions, 6 Bestiary notes', count('NPCs') === 16 && count('Players') === 4 && count('Locations') === 9 && count('Factions') === 5 && count('Plot threads') === 7 && count('Sessions') === 6 && count('Bestiary') === 6, nav.join('|'));
check('nothing is waiting to be pushed', await pg.locator('#pushBtn').isDisabled());
await pg.waitForSelector('text=What am I forgetting?');
const forgetting = await pg.innerText('body');
check('"What am I forgetting?" has carried-over tasks, a quiet thread and a quiet player', forgetting.includes('Calder\'s confession') && forgetting.includes('Pell Is Missing') && forgetting.includes('Sorrel Vance'));
check('no raw link brackets in the carried-over tasks', !/\[\[The Letter/.test(forgetting));
await pg.click('#navParty'); await pg.waitForSelector('#ptColumns'); await pg.click('#ptColumns'); await pg.waitForTimeout(300);
check('the party page lists four players with numbers', await pg.locator('tr[data-player]').count() === 4 && (await pg.inputValue('input[aria-label="Gold for Kestra Dune"]')) === '214');
check('the encounter is already lined up', (await pg.textContent('body')).includes('Hollow Choir Cultist'));
await pg.click('#navSecrets'); await pg.waitForTimeout(300);
check('secrets: some with fewer than three ways to find them', (await pg.textContent('body')).includes('2 of 3 ways to find it'));
await pg.click('#navClocks'); await pg.waitForTimeout(300);
const vals = await pg.$$eval('input, select', els => els.map(e => e.value));
check('four clocks and five factions', vals.includes('Isolde\'s patience') && vals.includes('The bells ring again') && (await pg.locator('a:has-text("The Hollow Choir")').count()) === 1);
await pg.click('#navCharacters');
await pg.waitForSelector('[data-char]');
check('the Character Library has ten characters from level 1 to 20', await pg.locator('[data-char]').count() === 10 && (await pg.textContent('body')).includes('Level 20') && (await pg.textContent('body')).includes('Level 1'));
await pg.click('[data-edit="Archmage Vaelith"]');
await pg.waitForSelector('#ccName');
check('a library character opens in the creator', (await pg.inputValue('#ccName')) === 'Archmage Vaelith' && await pg.locator('[data-level="20"].on').count() === 1);
await pg.click('#libToList'); await pg.click('#libBack');
await pg.waitForSelector('.sidebar');
await pg.evaluate(() => window.__dmforge.A.goto('Ashfall/Sessions/2026-10-19 Session 13.md'));
await pg.waitForTimeout(400);
check('Session 13 shows its close-out and the absent player', (await pg.textContent('body')).includes('Toby Wren') && (await pg.textContent('body')).includes('Next time'));
check('no page errors', errors.length === 0, errors.join(' | '));
await b.close();
const failed = results.filter(r => !r).length;
console.log(failed ? failed + ' FAILED' : results.length + '/' + results.length + ' checks passed');
process.exit(failed ? 1 : 0);
