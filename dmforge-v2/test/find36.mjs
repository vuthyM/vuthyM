/* 2.36: finding things in a big campaign: quick switcher, back and forward, recent notes, sort and filter chips, bulk edits. */
import { createRequire } from 'node:module';
import path from 'node:path'; import url from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright');
const here = path.dirname(url.fileURLToPath(import.meta.url));
const results = [];
const check = (name, cond, extra) => { results.push(!!cond); console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '  ' + (extra ?? ''))); };
const b = await chromium.launch({ args: ['--no-sandbox'] });
const pg = await (await b.newContext({ viewport: { width: 1440, height: 1100 } })).newPage();
const errors = []; pg.on('pageerror', e => errors.push(e.message));
await pg.goto('file://' + path.join(here, '..', 'dist', 'DM-Forge.html'));
await pg.click('text=Try the demo vault');
await pg.waitForSelector('.sidebar');
const P = '.pane:not([hidden]) ';
const text = sel => pg.textContent(sel);
const nav = label => pg.evaluate(l => [...document.querySelectorAll('.nav-btn')].find(e => new RegExp(l).test(e.textContent)).click(), label);
const open = name => pg.evaluate(n => { const x = window.__dmforge.getIndex().notes.find(y => y.name === n); window.__dmforge.A.goto(x.path); }, name);
const title = () => pg.evaluate(() => (document.querySelector('.pane:not([hidden]) #noteTitle') || {}).textContent || '');
const note = n => pg.evaluate(x => { const y = window.__dmforge.getIndex().notes.find(z => z.name === x); return y ? { fm: y.fm, body: y.body, pending: y.pending, tags: y.tags } : null; }, n);

// ---- quick switcher
await pg.keyboard.press('Control+KeyK');
await pg.waitForSelector('#palInput');
check('Ctrl/Cmd+K opens the quick switcher with the cursor in it', await pg.evaluate(() => document.activeElement && document.activeElement.id === 'palInput'));
check('empty, it offers actions to start with', await pg.locator('.pal-head:has-text("Actions")').count() === 1);
await pg.keyboard.press('Control+KeyK');
check('the same keys close it', await pg.locator('#palInput').count() === 0);
await pg.keyboard.press('Control+KeyK');
await pg.fill('#palInput', 'cinder');
await pg.waitForSelector('.pal-row[data-pal="The Cinder & Crown"]');
check('typing finds notes, the first one chosen', (await pg.getAttribute('.pal-row[aria-selected="true"]', 'data-pal')) !== null && await pg.locator('.pal-head:has-text("Notes")').count() === 1);
await pg.fill('#palInput', 'the cinder & crown');
await pg.waitForTimeout(100);
await pg.keyboard.press('Enter');
await pg.waitForFunction(() => /Cinder/.test((document.querySelector('.pane:not([hidden]) #noteTitle') || {}).textContent || ''));
check('Enter opens it', (await title()) === 'The Cinder & Crown');
await pg.keyboard.press('Control+KeyK'); await pg.fill('#palInput', 'roll dice');
await pg.waitForSelector('.pal-row[data-pal="Roll dice"]'); await pg.keyboard.press('Enter');
await pg.waitForSelector('#diceBox');
check('an action runs from the same box (Roll dice opens the roller)', true);
await pg.keyboard.press('Escape');
await pg.keyboard.press('Control+KeyK'); await pg.fill('#palInput', 'zorbo the new');
await pg.waitForSelector('.pal-head:has-text("Create")');
check('a name with no note offers to create one', await pg.locator('.pal-row[data-pal*="Create an NPC called"]').count() === 1 && await pg.locator('.pal-row[data-pal*="Create a location called"]').count() === 1);
await pg.click('.pal-row[data-pal*="Create an NPC called"]');
await pg.waitForFunction(() => /Zorbo/i.test((document.querySelector('.pane:not([hidden]) #noteTitle') || {}).textContent || ''));
check('creating makes the note (an NPC) and opens it', (await note('zorbo the new')) && (await note('zorbo the new')).fm.type === 'npc', JSON.stringify(await note('zorbo the new')));
await pg.keyboard.press('Control+KeyK'); await pg.fill('#palInput', 'map');
await pg.waitForSelector('.pal-row[data-pal^="Open the map of"]');
check('maps are actions too (Open the map of Greenhold…)', await pg.locator('.pal-row[data-pal="Open the map of Greenhold"]').count() === 1);
await pg.keyboard.press('Escape');

// ---- back, forward and recent
await open('Greenhold'); await open('The Weir'); await open('Old Tam');
check('Back is on once you have moved around', await pg.locator('#navBack').isEnabled() && await pg.locator('#navFwd').isDisabled());
await pg.click('#navBack');
check('Back goes to the note before', (await title()) === 'The Weir');
await pg.click('#navBack');
check('and before that', (await title()) === 'Greenhold');
await pg.click('#navFwd');
check('Forward comes back', (await title()) === 'The Weir');
await pg.keyboard.press('Control+BracketLeft');
await pg.waitForTimeout(100);
check('Ctrl/Cmd+[ is Back too', (await title()) === 'Greenhold');
await pg.keyboard.press('Control+BracketRight');
await pg.waitForTimeout(100);
check('and Ctrl/Cmd+] is Forward', (await title()) === 'The Weir');
await open('Mireille Vane');
check('going somewhere new drops what was forward of it', await pg.locator('#navFwd').isDisabled());
await pg.click('#recentMenu');
const recent = await pg.$$eval('[data-recent]', els => els.map(e => e.getAttribute('data-recent')));
check('Recent lists the notes you opened, newest first, without repeats', recent[0] === 'Mireille Vane' && new Set(recent).size === recent.length && recent.includes('Old Tam') && recent.includes('Greenhold'), recent.join());
await pg.click('[data-recent="Old Tam"]');
check('and a click in Recent opens one', (await title()) === 'Old Tam');

// ---- sort and filter chips
await nav('NPCs'); await pg.waitForSelector(P + '#lvBar');
const chips = await pg.$$eval(P + '[data-chip]', els => els.map(e => e.getAttribute('data-chip') + ':' + e.textContent.replace(/\D+/g, '')));
check('NPCs get filter chips for status, each with its count', chips.length >= 2 && chips.some(c => /^Alive:\d+$/.test(c)), chips.join());
const total = await pg.locator(P + '.list-item').count();
await pg.click(P + '[data-chip="Alive"]');
const alive = await pg.locator(P + '.list-item').count();
check('a chip shows only those', alive > 0 && alive < total, alive + ' of ' + total);
await pg.click(P + '#lvClear');
check('Clear brings the rest back', await pg.locator(P + '.list-item').count() === total);
await pg.evaluate(() => { const A = window.__dmforge.A; const n = window.__dmforge.getIndex().notes.find(y => y.name === 'Finch'); A.setFieldValue(n.path, 'npc', 'role', 'Head stable hand'); });
await pg.selectOption(P + '#lvSort', 'edited');
await pg.waitForFunction(() => !document.querySelector('.pane:not([hidden]) #lvBar').textContent.includes('reading dates'));
let names = await pg.$$eval(P + '.list-item .t', els => els.map(e => e.textContent.trim()));
check('Recently edited puts the note you just changed first', names[0] === 'Finch', names.slice(0, 3).join());
await pg.selectOption(P + '#lvSort', 'stale');
names = await pg.$$eval(P + '.list-item .t', els => els.map(e => e.textContent.trim()));
check('Not touched for longest puts it last (notes with unpushed changes count as touched just now)', names.slice(-3).includes('Finch') && names[0] !== 'Finch', names.slice(-3).join());
await pg.selectOption(P + '#lvSort', 'name');
names = await pg.$$eval(P + '.list-item .t', els => els.map(e => e.textContent.trim()));
check('and Name A to Z sorts as before', names.join() === names.slice().sort((a, b) => a.localeCompare(b)).join());
check('the choice is remembered', await pg.evaluate(() => Object.keys(localStorage).some(k => k.startsWith('dmforge:view:') && k.endsWith('|npc'))));

// ---- bulk edits
await pg.click(P + '#grpPick');
await pg.waitForSelector(P + '#grpBulk');
await pg.click(P + '.list-item:has-text("Finch")'); await pg.click(P + '.list-item:has-text("Edda Wick")'); await pg.click(P + '.list-item:has-text("Harl Dunmere")');
check('Select several counts them', /3\s*selected/.test(await text('#grpBulk')));
await pg.selectOption(P + '[data-bulkfield="status"]', 'Missing');
await pg.waitForTimeout(150);
check('Set status changes them all', (await note('Finch')).fm.status === 'Missing' || /Missing/.test(JSON.stringify(await note('Finch'))), JSON.stringify(await note('Finch')));
await pg.click(P + '.list-item:has-text("Finch")'); await pg.click(P + '.list-item:has-text("Edda Wick")'); await pg.click(P + '.list-item:has-text("Harl Dunmere")');
await pg.fill(P + '#bulkTag', 'goblin-raid'); await pg.click(P + '#bulkTagAdd');
await pg.waitForTimeout(150);
check('Add tag tags them all', (await note('Finch')).tags.includes('goblin-raid') && (await note('Edda Wick')).tags.includes('goblin-raid'), JSON.stringify((await note('Finch')).tags));
await pg.click(P + '.list-item:has-text("Finch")'); await pg.click(P + '.list-item:has-text("Edda Wick")');
await pg.fill(P + '#bulkTag', 'goblin-raid'); await pg.click(P + '#bulkTagRemove');
await pg.waitForTimeout(150);
check('Remove tag takes it off', !(await note('Finch')).tags.includes('goblin-raid') && !(await note('Edda Wick')).tags.includes('goblin-raid'));
await pg.click(P + '#bulkAll');
check('All ticks everything shown', new RegExp(total + '\\s*selected').test(await text('#grpBulk')), await text('#grpBulk'));
await pg.click(P + '#bulkNone');
check('None clears it', /0\s*selected/.test(await text('#grpBulk')));
await pg.click(P + '.list-item:has-text("Zorbo")');
await pg.click(P + '#bulkDelete');
await pg.waitForSelector('.modal .btn-danger');
await pg.click('.modal .btn-danger');
await pg.waitForTimeout(200);
check('Delete (after asking) removes the notes you ticked, as a pending change', (await note('zorbo the new')) === null || (await note('zorbo the new')).pending === 'delete');
await pg.click(P + '#grpPick');
// other lists
await nav('Plot threads'); await pg.waitForSelector(P + '#lvBar');
check('plot threads get chips for their status too', await pg.locator(P + '[data-chip]').count() >= 2);
await pg.click(P + '#grpPick');
check('and the same bulk bar, with a status to set', await pg.locator(P + '[data-bulkfield="status"]').count() === 1);
await pg.click(P + '#grpPick');
await nav('Locations'); await pg.waitForSelector(P + '#lvBar');
await pg.click(P + '#grpPick');
await pg.click(P + '.list-item:has-text("Orchard Road")'); await pg.click(P + '.list-item:has-text("The East Well")');
await pg.selectOption(P + '#grpMoveTo', 'The Cinder & Crown');
await pg.waitForTimeout(200);
check('places can be moved inside another in bulk', /Cinder/.test(String((await note('Orchard Road')).fm.region)) && /Cinder/.test(String((await note('The East Well')).fm.region)));
check('no errors from the page', errors.length === 0, errors.join('\n'));
await b.close();
const ok = results.filter(Boolean).length;
console.log(`${ok}/${results.length} checks passed`);
process.exit(ok === results.length ? 0 : 1);
