import { createRequire as __pwRequire } from 'node:module';
const { chromium } = __pwRequire(import.meta.url)('playwright');
import path from 'node:path'; import url from 'node:url';

/* Session prep template: the Locations lines ("- **Place:** ") have a spot to click and type, like the checkbox lines in State tracker and MUST HAPPEN */
const here = path.dirname(url.fileURLToPath(import.meta.url));
const results = [];
const check = (name, cond, extra) => { results.push(!!cond); console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '  ' + (extra ?? ''))); };
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const pg = await (await b.newContext({ viewport: { width: 1360, height: 1000 }, deviceScaleFactor: 1 })).newPage();
const errs = []; pg.on('pageerror', e => errs.push(e.message));
await pg.goto('file://' + path.join(here, '..', 'dist', 'DM-Forge.html'));
await pg.click('text=Try the demo vault'); await pg.waitForSelector('.sidebar');
await pg.click('.nav-btn:has-text("Sessions")');
await pg.click('.pane:not([hidden]) .list-item:has-text("Session 12")');
await pg.click('#addTemplateBtn'); await pg.click('#tplAdd');
await pg.waitForFunction(() => !document.querySelector('.modal'));
const md = '.pane:not([hidden]) .md';
const SP = 'Ashfall/Sessions/2026-10-12 Session 12.md';
check('each of the three Places lines has a spot to click', (await pg.locator(md + ' details.callout-abstract li .u-empty').count()) === 3, await pg.locator(md + ' details.callout-abstract li .u-empty').count());
check('so do the State tracker and MUST HAPPEN lines (as before)', (await pg.locator(md + ' details.callout-todo li .u-empty').count()) === 3 && (await pg.locator(md + ' details.callout-important li .u-empty').count()) === 3);
const box = await pg.locator(md + ' details.callout-abstract li .u-empty >> nth=0').boundingBox();
const lab = await pg.locator(md + ' details.callout-abstract li strong >> nth=0').boundingBox();
check('the spot sits on the same line, right after the label', box.x >= lab.x + lab.width - 1 && Math.abs((box.y + box.height) - (lab.y + lab.height)) < 12 && box.width > 40, JSON.stringify({ box, lab }));
await pg.screenshot({ path: process.env.OUT ? process.env.OUT + '/slots.png' : '/dev/null', clip: { x: 250, y: 100, width: 800, height: 700 } }).catch(() => {});
await pg.click(md + ' details.callout-abstract li .u-empty >> nth=0');
await pg.waitForSelector('.u-edit');
await pg.keyboard.type('Greenhold');
await pg.keyboard.press('Enter');
await pg.waitForTimeout(400); await pg.waitForSelector('.u-edit');
await pg.keyboard.type('The Weir');
await pg.keyboard.press('Control+Enter');
await pg.waitForFunction(() => !document.querySelector('.u-edit'));
const text = await pg.evaluate(p => window.__dmforge.S.working.get(p), SP);
check('typing saves after the label, on that line', text.includes('> - **Place:** Greenhold'), text.split('\n').filter(l => /Place/.test(l)).join(' | '));
check('Enter adds the next line, and its text is saved too', text.includes('The Weir'), text.split('\n').filter(l => /Place|Weir/.test(l)).join(' | '));
check('the lines still have the label, and the other Places lines are untouched', (text.match(/> - \*\*Place:\*\*/g) || []).length >= 2);
check('a filled-in line no longer shows an empty spot', (await pg.locator(md + ' details.callout-abstract li:has-text("Greenhold") .u-empty').count()) === 0);
check('no page errors', errs.length === 0, errs.join('\n'));
await b.close();
const failed = results.filter(x => !x).length;
console.log('\n' + (results.length - failed) + '/' + results.length + ' checks passed');
process.exit(failed ? 1 : 0);
